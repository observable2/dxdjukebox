create policy "public read slots" on jukebox_slots for select using (true);
create policy "admin write items" on jukebox_items for all to authenticated using (true) with check (true);
create policy "admin write slots" on jukebox_slots for all to authenticated using (true) with check (true);
create policy "public read screens" on jukebox_screens for select using (true);
create policy "admin write screens" on jukebox_screens for all to authenticated using (true) with check (true);
-- RLS policies only restrict which rows a role sees; the role still needs the underlying table
-- grant to touch the table at all. Supabase usually sets this up automatically for new tables in
-- "public", but it doesn't always take — if you hit "permission denied for table ..." (Postgres
-- error 42501) after running the above, run this block too.
grant usage on schema public to anon, authenticated;
grant select on jukebox_items, jukebox_slots, jukebox_screens, jukebox_item_screens to anon, authenticated;
grant insert, update, delete on jukebox_items, jukebox_slots, jukebox_screens, jukebox_item_screens to authenticated;

-- Public control of screen 2 ("studio"): the left/right/schedule buttons on Titles (?s=studio) work without signing in by
-- calling this function, which runs with its owner's rights. It can only pin an item that is in screen 2's generated
-- rotation (or clear the pin), so a visitor cannot pin anything else or touch any other screen. An existing database needs
-- this block run once.
create or replace function studio_pin(p_item uuid) returns void
language plpgsql security definer set search_path = public as $$
declare s uuid;
begin
  select id into s from jukebox_screens where number = 2;
  if s is null then raise exception 'There is no screen 2'; end if;
  if p_item is not null and not exists (
    select 1 from jukebox_slots where screen_id = s and rotation and item_id = p_item
  ) then raise exception 'That item is not in the studio rotation'; end if;
  update jukebox_screens set pinned_item_id = p_item where id = s;
end $$;
revoke all on function studio_pin(uuid) from public;
grant execute on function studio_pin(uuid) to anon, authenticated;

