-- Run once in Supabase → SQL Editor
create table jukebox_items (
  id uuid primary key default gen_random_uuid(),
  title text not null,
  slug text not null unique check (slug ~ '^[a-z0-9]+$'),   -- lowercase letters and digits only; defaults (in the Admin page) to the title with everything else removed
                             -- (an existing database needs the migration at the bottom of this file)
  authorship text, url text not null,
  year_created smallint not null check (year_created between 1000 and 9999),
  month_day_created text check (month_day_created ~ '^([1-9]|1[0-2])(/([1-9]|[12][0-9]|3[01]))?$'),   -- M/D, e.g. 3/14, or M alone (month only)
                             -- (an existing database needs: alter table jukebox_items drop constraint jukebox_items_month_day_created_check;
                             --  alter table jukebox_items add constraint jukebox_items_month_day_created_check check (month_day_created ~ '^([1-9]|1[0-2])(/([1-9]|[12][0-9]|3[01]))?$');)
  date_related_notes text,   -- free form
                             -- (an existing database needs: alter table jukebox_items add column date_related_notes text;
                             --  alter table jukebox_items drop column year_published, drop column month_day_published;)
  abstract text,   -- Markdown or HTML, at most 101 words as displayed (checked by the Admin page: only the renderer can count the displayed words)
                             -- (an existing database needs the abstract migration at the bottom of this file)
  where_created text,
  publisher text, media text, delivery text,
  duration text check (duration ~ '^(0|[1-9][0-9]*):[0-5][0-9](:[0-5][0-9])?$'),  -- M:SS or H:MM:SS, first number unpadded
  duration_type text not null default 'work' check (duration_type in ('work', 'loop', 'ambient', 'ambient loop')),
                   -- (an existing database needs: alter table jukebox_items add column duration_type text not null default 'work' check (duration_type in ('work', 'loop', 'ambient', 'ambient loop'));)
  notes text,
  course text, mentor text, license text, credits text,
  hide_url boolean not null default false,
  further_info_url text,
  updated_at timestamptz default now()
);
create table jukebox_screens (
  id uuid primary key default gen_random_uuid(),
  number int not null unique check (number >= 1),
  slug text not null unique check (slug ~ '^[a-z][a-z0-9-]*$'),   -- starts with a letter, so it is never mistaken for a number or range
  name text,
  show_titles_link boolean not null default true,   -- whether the Screen page shows a small link to Titles
  pinned_item_id uuid references jukebox_items(id) on delete set null   -- "Show now": shown on this screen over any slot until cleared
);
insert into jukebox_screens (number, slug, name) values (1, 'main', 'Main');
create table jukebox_slots (
  id uuid primary key default gen_random_uuid(),
  screen_id uuid not null references jukebox_screens(id) on delete cascade,
  item_id uuid not null references jukebox_items(id) on delete cascade,
  days smallint[] not null,
  start_time text not null check (start_time ~ '^([01][0-9]|2[0-3]):[0-5][05]$'),
  end_time text not null check (end_time ~ '^(([01][0-9]|2[0-3]):[0-5][05]|24:00)$'),
  weeks int not null default 0,
  from_date date not null,
  rotation boolean not null default false,   -- true = generated by "Generate rotation"
  check (end_time > start_time)
);
-- Which screens an item belongs to: one row per item and screen. rotation = the item is also in that screen's rotation
-- ("Generate rotation" cycles through those). Deleting an item or a screen deletes its rows.
create table jukebox_item_screens (
  id uuid primary key default gen_random_uuid(),
  item_id uuid not null references jukebox_items(id) on delete cascade,
  screen_id uuid not null references jukebox_screens(id) on delete cascade,
  rotation boolean not null default false,
  unique (item_id, screen_id)
);
alter table jukebox_items enable row level security;
alter table jukebox_slots enable row level security;
alter table jukebox_screens enable row level security;
alter table jukebox_item_screens enable row level security;
create policy "public read item screens" on jukebox_item_screens for select using (true);
create policy "admin write item screens" on jukebox_item_screens for all to authenticated using (true) with check (true);
